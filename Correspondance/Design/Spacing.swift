import Foundation

enum Spacing {
  static let xxs: CGFloat = 4
  static let xs: CGFloat = 8
  static let sm: CGFloat = 12
  static let md: CGFloat = 16
  static let lg: CGFloat = 24
  static let xl: CGFloat = 32
  static let xxl: CGFloat = 48

  /// Marge intérieure d’une page lettre.
  static let letterPadding: CGFloat = lg
  /// Espacement vertical entre blocs de texte.
  static let paragraph: CGFloat = sm
}
